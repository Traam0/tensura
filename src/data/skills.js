const defaultMastery = { Common: 100, Extra: 500, Intrinsic: 100, Resistance: 100, Unique: 1000 };
const defaultCost = { Common: 100, Extra: 1000, Intrinsic: 100, Unique: 1000 };

export const skills = registry.map(([type, registryId, name, masteryOverride, costOverride]) => {
  const id = registryId.replaceAll('_', '-');
  const [summary = '', acquisition, masteryTip] = fieldNotes[id] ?? [];
  const source = wiki + (pageTitles[id] ?? name.replaceAll(' ', '_')).split('/').map(encodeURIComponent).join('/');
  const masteryTarget = masteryOverride ?? defaultMastery[type];
  const cost = costOverride || (type === 'Resistance' ? (id.endsWith('-nullification') ? 1000 : 100) : defaultCost[type]);
  const icon = new URL('../../public/skills/' + type.toLowerCase() + '/' + registryId + '.png', import.meta.url).href;
  return { id, name, type, icon, summary, source, masteryTarget, cost, acquisition: acquisition ?? acquisitionFor(type, id, name), masteryTip };
}).sort((first, second) => first.name.localeCompare(second.name));

