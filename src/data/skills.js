function acquisitionFor(type, id, name) {
  if (acquisitionNotes[id]) return acquisitionNotes[id];
  // Every Unique Skill with a special acquisition route has an entry above.
  if (type === 'Unique') return reroll;
  if (type === 'Resistance' && id.endsWith('-nullification')) {
    return 'Awaken while you have ' + name.replace('Nullification', 'Resistance') + '.';
  }
  if (id.startsWith('magic-') && id.endsWith('-transform')) {
    return 'Master ' + name.slice('Magic '.length) + ' and reach 400,000 EP.';
  }
}

